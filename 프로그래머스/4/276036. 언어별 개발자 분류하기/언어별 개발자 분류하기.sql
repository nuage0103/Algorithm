WITH FRONT AS(
    SELECT SUM(CODE) AS CODE
    FROM SKILLCODES
    WHERE CATEGORY = 'Front End'
), 
PYTHON AS(
    SELECT CODE
    FROM SKILLCODES
    WHERE NAME = 'Python'
), 
CSHARP AS(
    SELECT CODE
    FROM SKILLCODES
    WHERE NAME = 'C#'
)

SELECT (
    CASE
    WHEN (SKILL_CODE & F.CODE) AND (SKILL_CODE & P.CODE) THEN 'A'
    WHEN (SKILL_CODE & C.CODE) THEN 'B'
    WHEN (SKILL_CODE & F.CODE) THEN 'C'
    END
) AS GRADE, ID, EMAIL
FROM DEVELOPERS
JOIN FRONT AS F
JOIN PYTHON AS P
JOIN CSHARP AS C
HAVING GRADE IS NOT NULL
ORDER BY GRADE, ID
;
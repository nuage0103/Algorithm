WITH T AS(
    SELECT EMP_NO, 
    (
        CASE
        WHEN AVG(SCORE) >= 96 THEN 'S'
        WHEN AVG(SCORE) >= 90 THEN 'A'
        WHEN AVG(SCORE) >= 80 THEN 'B'
        ELSE 'C'
        END 
    ) AS GRADE
    FROM HR_GRADE
    GROUP BY EMP_NO
)

SELECT H.EMP_NO, H.EMP_NAME, T.GRADE, 
ROUND(
    CASE
    WHEN T.GRADE = 'S' THEN (0.2 * H.SAL)
    WHEN T.GRADE = 'A' THEN (0.15 * H.SAL)
    WHEN T.GRADE = 'B' THEN (0.1 * H.SAL)
    ELSE 0
    END
) AS BONUS
FROM HR_EMPLOYEES AS H
JOIN T ON H.EMP_NO = T.EMP_NO
ORDER BY EMP_NO
;
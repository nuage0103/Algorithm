WITH RECURSIVE T AS(
    SELECT ID, 1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E.ID, T.GENERATION + 1
    FROM ECOLI_DATA AS E
    JOIN T ON E.PARENT_ID = T.ID
)

SELECT COUNT(*) AS COUNT, GENERATION
FROM T
WHERE ID NOT IN (
    SELECT PARENT_ID
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NOT NULL
)
GROUP BY GENERATION
ORDER BY GENERATION
;